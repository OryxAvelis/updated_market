(() => {
  'use strict';

  // The live endpoint currently returns 20 catalog rows per page even when a
  // smaller page_size is requested, so keep the pager aligned with that read.
  const PAGE_SIZE = 20;
  const VALID_STATUSES = new Set(['active', 'draft', 'archived']);
  const LOCAL_ID_PREFIX = 'local-product-';
  let core;
  let productStorageKey;
  let categoryStorageKey;
  let overlay;
  let categoryOptions = [];
  let currentPage = 1;
  let totalPages = 1;
  let catalogTotal = 0;
  let currentRows = [];
  let requestSequence = 0;
  let searchTimer = null;
  let productModal = null;

  const byId = id => document.getElementById(id);
  const esc = value => core.escape(value == null ? '' : String(value));
  const asId = value => value == null || value === '' ? '' : String(value);

  function emptyOverlay() {
    return { version: 1, created: [], patches: {}, hiddenIds: [], hiddenMeta: {} };
  }

  function sanitizeOverlay(value) {
    const source = value && typeof value === 'object' ? value : {};
    const patches = source.patches && typeof source.patches === 'object' && !Array.isArray(source.patches)
      ? source.patches
      : {};
    return {
      version: 1,
      created: Array.isArray(source.created) ? source.created.filter(item => item && item.id != null) : [],
      patches,
      hiddenIds: [...new Set((Array.isArray(source.hiddenIds) ? source.hiddenIds : []).map(asId).filter(Boolean))],
      hiddenMeta: source.hiddenMeta && typeof source.hiddenMeta === 'object' && !Array.isArray(source.hiddenMeta)
        ? source.hiddenMeta
        : {}
    };
  }

  function persistOverlay() {
    overlay = sanitizeOverlay(overlay);
    if (core.write(productStorageKey, overlay) === undefined) throw new Error('Product overlay write failed');
  }

  function isLocalId(id) {
    return asId(id).startsWith(LOCAL_ID_PREFIX);
  }

  function getCategoryId(product) {
    const value = product.categoryId ?? product.category_id ?? product.category?.id
      ?? (typeof product.category === 'number' || typeof product.category === 'string' ? product.category : '');
    return asId(value);
  }

  function getDiscount(product) {
    const direct = Number(product.discount ?? product.discount_percentage ?? product.discount_percent);
    if (Number.isFinite(direct)) return Math.min(100, Math.max(0, direct));
    const price = Number(product.price);
    const oldPrice = Number(product.old_price ?? product.regular_price);
    if (Number.isFinite(price) && Number.isFinite(oldPrice) && oldPrice > price && oldPrice > 0) {
      return Math.round((1 - price / oldPrice) * 100);
    }
    return 0;
  }

  function normalizeProduct(product, source = 'live') {
    const id = asId(product.id);
    const categoryId = getCategoryId(product);
    const category = categoryOptions.find(item => asId(item.id) === categoryId);
    const baseStatus = VALID_STATUSES.has(product.status) ? product.status : 'active';
    return {
      ...product,
      id,
      name: String(product.name || '').trim() || `#${id}`,
      price: Number(product.price) || 0,
      discount: getDiscount(product),
      categoryId,
      categoryName: product.categoryName || product.category_name || product.category?.name || category?.name || '',
      status: baseStatus,
      is_available: product.is_available !== false && product.availability !== false,
      image_url: product.image_url || product.image || '',
      source,
      localEdited: false
    };
  }

  function mergeProduct(product) {
    const normalized = normalizeProduct(product, 'live');
    const patch = overlay.patches[normalized.id];
    if (!patch || typeof patch !== 'object') return normalized;
    return normalizeProduct({ ...normalized, ...patch, id: normalized.id }, 'live-edited');
  }

  function categoryFlatRecord(category, index) {
    return {
      ...category,
      id: asId(category.id),
      name: String(category.name || category.displayName || '').trim(),
      parentId: asId(category.parentId ?? category.parent_id ?? category.parent?.id),
      depth: Math.max(0, Number(category.depth) || 0),
      order: index
    };
  }

  function rebuildCategoryOptions() {
    const liveFlat = core.flattenCategories(Array.isArray(categories) ? categories : []).map(categoryFlatRecord);
    const catOverlay = sanitizeOverlay(core.read(categoryStorageKey, emptyOverlay()));
    const hidden = new Set(catOverlay.hiddenIds.map(asId));
    const merged = liveFlat
      .filter(item => !hidden.has(item.id))
      .map(item => {
        const patch = catOverlay.patches[item.id];
        return patch && typeof patch === 'object' ? categoryFlatRecord({ ...item, ...patch, id: item.id }, item.order) : item;
      });

    catOverlay.created.forEach((item, index) => {
      if (!hidden.has(asId(item.id))) merged.push(categoryFlatRecord(item, liveFlat.length + index));
    });

    const map = new Map(merged.map(item => [item.id, item]));
    const depthFor = (item, trail = new Set()) => {
      if (!item.parentId || !map.has(item.parentId) || trail.has(item.id)) return 0;
      const nextTrail = new Set(trail);
      nextTrail.add(item.id);
      return Math.min(8, 1 + depthFor(map.get(item.parentId), nextTrail));
    };
    categoryOptions = merged.map(item => ({ ...item, depth: depthFor(item) }));
    renderCategorySelects();
  }

  function categoryLabel(category) {
    const prefix = category.depth ? `${'— '.repeat(Math.min(category.depth, 4))}` : '';
    return prefix + (typeof catName === 'function' ? catName(category.name) : category.name);
  }

  function renderCategorySelects() {
    const filter = byId('productCategoryFilter');
    const editor = byId('productCategory');
    if (!filter || !editor) return;
    const filterValue = filter.value;
    const editorValue = editor.value;
    const options = categoryOptions.map(category =>
      `<option value="${esc(category.id)}">${esc(categoryLabel(category))}</option>`
    ).join('');
    filter.innerHTML = `<option value="">${esc(t('admin_products_all_categories'))}</option>${options}`;
    editor.innerHTML = `<option value="">${esc(t('admin_products_choose_category'))}</option>${options}`;
    if (categoryOptions.some(item => item.id === filterValue)) filter.value = filterValue;
    if (categoryOptions.some(item => item.id === editorValue)) editor.value = editorValue;
  }

  function safeImageValue(value) {
    const text = String(value || '').trim();
    if (!text || /[\u0000-\u001f\u007f]/.test(text)) return '';
    if (/^[a-z][a-z\d+.-]*:/i.test(text)) {
      try {
        const url = new URL(text);
        return url.protocol === 'http:' || url.protocol === 'https:' ? text : '';
      } catch {
        return '';
      }
    }
    return text.startsWith('//') ? '' : text;
  }

  function currentFilters() {
    return {
      search: byId('productSearch').value.trim(),
      category: byId('productCategoryFilter').value,
      status: byId('productStatusFilter').value,
      ordering: byId('productSort').value
    };
  }

  function productMatches(product, filters) {
    const query = filters.search.toLocaleLowerCase();
    if (query && !product.name.toLocaleLowerCase().includes(query)) return false;
    if (filters.category && asId(product.categoryId) !== filters.category) return false;
    if (filters.status && product.status !== filters.status) return false;
    return true;
  }

  function baseMatchesApiFilters(patch, filters) {
    const base = patch?._base;
    if (!base || typeof base !== 'object') return false;
    const query = filters.search.toLocaleLowerCase();
    if (query && !String(base.name || '').toLocaleLowerCase().includes(query)) return false;
    if (filters.category && asId(base.categoryId) !== filters.category) return false;
    return true;
  }

  function sortRows(rows, ordering) {
    const list = [...rows];
    if (ordering === 'name') list.sort((a, b) => a.name.localeCompare(b.name));
    if (ordering === 'price') list.sort((a, b) => a.price - b.price);
    if (ordering === '-price') list.sort((a, b) => b.price - a.price);
    return list;
  }

  function showState(type, title, body, actionLabel = '', onAction = null) {
    const stateContainer = byId('productListState');
    stateContainer.hidden = false;
    byId('productTableWrap').hidden = true;
    byId('productPagination').hidden = true;
    core.state(stateContainer, { type, title, body, actionLabel, onAction });
  }

  async function loadProducts() {
    const requestId = ++requestSequence;
    const filters = currentFilters();
    showState('loading', t('admin_products_loading_title'), t('admin_products_loading_body'));

    try {
      const localCategory = isLocalId(filters.category);
      const apiCategory = localCategory ? null : (filters.category || null);
      const apiOrdering = ['name', 'price', '-price'].includes(filters.ordering) ? filters.ordering : '';
      const data = await fetchProducts(currentPage, apiCategory, filters.search, apiOrdering, PAGE_SIZE);
      if (requestId !== requestSequence) return;

      const hidden = new Set(overlay.hiddenIds.map(asId));
      const liveRows = (Array.isArray(data.results) ? data.results : [])
        .filter(product => !hidden.has(asId(product.id)))
        .map(mergeProduct)
        .filter(product => productMatches(product, filters));

      // A live product can be edited after it was loaded from any catalog page.
      // Materialize those complete local patches as first-page overlay rows so
      // renamed, re-categorized, or draft/archived products remain discoverable
      // even when the read-only API still indexes their original values.
      const patchedRows = Object.entries(overlay.patches)
        .filter(([id, patch]) => !hidden.has(asId(id)) && patch && typeof patch === 'object')
        .map(([id, patch]) => normalizeProduct({ ...patch, id }, 'live-edited'));
      const returnedIds = new Set(liveRows.map(product => product.id));
      const extraPatchedMatches = patchedRows
        .filter(product => productMatches(product, filters))
        .filter(product => {
          const baseWillBeReturned = baseMatchesApiFilters(overlay.patches[product.id], filters);
          const localStatusOnly = filters.status && filters.status !== 'active';
          return !returnedIds.has(product.id) && (!baseWillBeReturned || localStatusOnly);
        });

      const localMatches = overlay.created
        .map(product => normalizeProduct(product, 'local'))
        .filter(product => !hidden.has(product.id) && productMatches(product, filters));

      const rows = currentPage === 1 ? [...localMatches, ...extraPatchedMatches, ...liveRows] : liveRows;
      currentRows = sortRows(rows, filters.ordering);

      if (localCategory || (filters.status && filters.status !== 'active')) {
        catalogTotal = localMatches.length + patchedRows.filter(product => productMatches(product, filters)).length;
        totalPages = 1;
      } else {
        const hiddenAdjustment = !filters.category && !filters.search ? overlay.hiddenIds.filter(id => !isLocalId(id)).length : 0;
        const inactivePatchAdjustment = filters.status === 'active' && !filters.search && !filters.category
          ? patchedRows.filter(product => product.status !== 'active').length
          : 0;
        const relocatedPatchAdjustment = (filters.search || filters.category)
          ? extraPatchedMatches.filter(product => !baseMatchesApiFilters(overlay.patches[product.id], filters)).length
          : 0;
        catalogTotal = Math.max(
          currentRows.length,
          (Number(data.count) || 0) + localMatches.length + relocatedPatchAdjustment - hiddenAdjustment - inactivePatchAdjustment
        );
        // The API's raw page count remains the source of truth for navigation.
        // Local overlays are not a complete repacked catalog, so subtracting
        // hidden rows here could make untouched API pages unreachable.
        totalPages = Math.max(1, Math.ceil((Number(data.count) || 0) / PAGE_SIZE));
      }
      if (currentPage > totalPages) {
        currentPage = totalPages;
        return loadProducts();
      }
      renderProducts();
    } catch (error) {
      if (requestId !== requestSequence) return;
      console.warn('Admin product catalog read failed:', error);
      currentRows = [];
      byId('productSummary').textContent = '';
      showState(
        'error',
        t('admin_products_error_title'),
        t('admin_products_error_body'),
        t('admin_products_retry'),
        loadProducts
      );
    }
  }

  function statusLabel(status) {
    return t(`admin_products_status_${VALID_STATUSES.has(status) ? status : 'active'}`);
  }

  function sourceMarkup(product) {
    const kind = product.source === 'local' ? 'local' : (product.source === 'live-edited' ? 'edited' : 'live');
    const icon = kind === 'live' ? 'fa-cloud' : (kind === 'local' ? 'fa-laptop' : 'fa-pen-to-square');
    return `<span class="admin-products-source is-${kind}"><i class="fa-solid ${icon}" aria-hidden="true"></i>${esc(t(`admin_products_source_${kind}`))}</span>`;
  }

  function productRow(product) {
    const image = safeImageValue(product.image_url);
    const category = categoryOptions.find(item => item.id === asId(product.categoryId));
    const categoryText = category
      ? (typeof catName === 'function' ? catName(category.name) : category.name)
      : (product.categoryName || t('admin_products_unknown_category'));
    const available = product.is_available !== false;
    const discount = Number(product.discount) > 0 ? `${Math.round(Number(product.discount))}%` : t('admin_products_no_discount');
    const name = product.name;
    const imageMarkup = image
      ? `<img src="${esc(image)}" alt="" loading="lazy" />`
      : '<i class="fa-solid fa-box-open" aria-hidden="true"></i>';

    return `<tr data-product-id="${esc(product.id)}">
      <td data-label="${esc(t('admin_products_col_product'))}">
        <div class="admin-products-item">
          <span class="admin-products-thumb">${imageMarkup}</span>
          <span>
            <span class="admin-products-item-name">${esc(name)}</span>
            <span class="admin-products-item-meta">${esc(t('admin_products_reference', { id: product.id }))} · ${esc(available ? t('admin_products_available') : t('admin_products_unavailable'))}</span>
          </span>
        </div>
      </td>
      <td data-label="${esc(t('admin_products_col_category'))}">${esc(categoryText)}</td>
      <td data-label="${esc(t('admin_products_col_price'))}"><span class="admin-products-price">${esc(formatPrice(product.price))}</span></td>
      <td data-label="${esc(t('admin_products_col_discount'))}">${esc(discount)}</td>
      <td data-label="${esc(t('admin_products_col_status'))}">
        <span class="admin-products-badge is-${esc(product.status)}">${esc(statusLabel(product.status))}</span>
      </td>
      <td data-label="${esc(t('admin_products_col_source'))}">${sourceMarkup(product)}</td>
      <td data-label="${esc(t('admin_products_col_actions'))}">
        <div class="admin-products-actions">
          <button class="admin-products-action" type="button" data-product-action="edit" aria-label="${esc(t('admin_products_edit_named', { name }))}" title="${esc(t('admin_products_edit_named', { name }))}">
            <i class="fa-solid fa-pen" aria-hidden="true"></i>
          </button>
          <button class="admin-products-action is-delete" type="button" data-product-action="delete" aria-label="${esc(t('admin_products_delete_named', { name }))}" title="${esc(t('admin_products_delete_named', { name }))}">
            <i class="fa-solid fa-trash" aria-hidden="true"></i>
          </button>
        </div>
      </td>
    </tr>`;
  }

  function renderProducts() {
    const filters = currentFilters();
    if (!currentRows.length) {
      byId('productSummary').textContent = '';
      showState(
        'empty',
        t('admin_products_empty_title'),
        t('admin_products_empty_body'),
        t('admin_products_clear_filters'),
        resetFilters
      );
      if (currentPage > 1 && totalPages > 1) renderPagination();
      return;
    }

    byId('productListState').hidden = true;
    byId('productTableWrap').hidden = false;
    byId('productTableBody').innerHTML = currentRows.map(productRow).join('');
    byId('productSummary').textContent = isLocalId(filters.category)
      ? t('admin_products_summary_local_category', { shown: currentRows.length })
      : t('admin_products_summary', { shown: currentRows.length, total: catalogTotal });
    renderPagination();
  }

  function pageRange() {
    const pages = new Set([1, totalPages, currentPage - 1, currentPage, currentPage + 1]);
    return [...pages].filter(page => page >= 1 && page <= totalPages).sort((a, b) => a - b);
  }

  function renderPagination() {
    const nav = byId('productPagination');
    nav.hidden = totalPages <= 1;
    if (nav.hidden) return;

    byId('productPrevious').disabled = currentPage <= 1;
    byId('productNext').disabled = currentPage >= totalPages;
    const pages = pageRange();
    let previous = 0;
    byId('productPageButtons').innerHTML = pages.map(page => {
      const gap = previous && page - previous > 1 ? '<span aria-hidden="true">…</span>' : '';
      previous = page;
      return `${gap}<button class="admin-products-page-button" type="button" data-product-page="${page}" ${page === currentPage ? 'aria-current="page"' : ''} aria-label="${esc(t('admin_products_page_named', { page }))}">${page}</button>`;
    }).join('');
  }

  function resetFilters() {
    byId('productSearch').value = '';
    byId('productCategoryFilter').value = '';
    byId('productStatusFilter').value = '';
    byId('productSort').value = 'default';
    currentPage = 1;
    loadProducts();
  }

  function clearValidation() {
    byId('productEditorForm').querySelectorAll('.is-invalid').forEach(element => element.classList.remove('is-invalid'));
    byId('productEditorForm').querySelectorAll('.invalid-feedback').forEach(element => { element.textContent = ''; });
  }

  function invalidate(inputId, errorId, message) {
    byId(inputId).classList.add('is-invalid');
    byId(errorId).textContent = message;
  }

  function updateImagePreview() {
    const image = safeImageValue(byId('productImage').value);
    const wrap = byId('productImagePreview');
    const img = byId('productImagePreviewImg');
    wrap.hidden = !image;
    img.src = image || '';
    img.alt = image ? t('admin_products_image_preview') : '';
  }

  function openProductEditor(product = null) {
    clearValidation();
    byId('productEditorForm').reset();
    byId('productEditId').value = product?.id || '';
    byId('productEditorTitle').textContent = t(product ? 'admin_products_edit_title' : 'admin_products_add_title');
    byId('productName').value = product?.name || '';
    byId('productCategory').value = asId(product?.categoryId);
    byId('productStatus').value = VALID_STATUSES.has(product?.status) ? product.status : 'active';
    byId('productPrice').value = product ? Number(product.price) : '';
    byId('productDiscount').value = product ? Number(product.discount) || 0 : 0;
    byId('productImage').value = product?.image_url || '';
    byId('productAvailability').checked = product?.is_available !== false;
    updateImagePreview();
    productModal.show();
    byId('productEditorModal').addEventListener('shown.bs.modal', () => byId('productName').focus(), { once: true });
  }

  function validateProductForm() {
    clearValidation();
    const name = byId('productName').value.trim();
    const categoryId = byId('productCategory').value;
    const status = byId('productStatus').value;
    const rawPrice = byId('productPrice').value.trim();
    const rawDiscount = byId('productDiscount').value.trim();
    const price = Number(rawPrice);
    const discount = Number(rawDiscount);
    const rawImage = byId('productImage').value.trim();
    let valid = true;

    if (name.length < 2) {
      invalidate('productName', 'productNameError', t('admin_products_validation_name'));
      valid = false;
    }
    if (!categoryId || !categoryOptions.some(item => item.id === categoryId)) {
      invalidate('productCategory', 'productCategoryError', t('admin_products_validation_category'));
      valid = false;
    }
    if (!VALID_STATUSES.has(status)) {
      invalidate('productStatus', 'productStatusError', t('admin_products_validation_status'));
      valid = false;
    }
    if (!rawPrice || !Number.isFinite(price) || price < 0) {
      invalidate('productPrice', 'productPriceError', t('admin_products_validation_price'));
      valid = false;
    }
    if (!rawDiscount || !Number.isFinite(discount) || discount < 0 || discount > 100) {
      invalidate('productDiscount', 'productDiscountError', t('admin_products_validation_discount'));
      valid = false;
    }
    if (rawImage && !safeImageValue(rawImage)) {
      invalidate('productImage', 'productImageError', t('admin_products_validation_image'));
      valid = false;
    }
    if (!valid) {
      byId('productEditorForm').querySelector('.is-invalid')?.focus();
      return null;
    }

    const category = categoryOptions.find(item => item.id === categoryId);
    return {
      name,
      categoryId,
      category_id: categoryId,
      categoryName: category?.name || '',
      status,
      price,
      discount,
      is_available: byId('productAvailability').checked,
      image_url: safeImageValue(rawImage),
      updatedAt: new Date().toISOString()
    };
  }

  function nextLocalId() {
    const random = Math.random().toString(36).slice(2, 8);
    return `${LOCAL_ID_PREFIX}${Date.now()}-${random}`;
  }

  async function saveProduct(event) {
    event.preventDefault();
    const values = validateProductForm();
    if (!values) return;

    const saveButton = byId('saveProductButton');
    const editId = byId('productEditId').value;
    core.setBusy(saveButton, true, t('admin_products_saving'));
    try {
      await new Promise(resolve => requestAnimationFrame(resolve));
      if (!editId) {
        const createdAt = new Date().toISOString();
        overlay.created.unshift({ ...values, id: nextLocalId(), createdAt, source: 'local' });
        persistOverlay();
        productModal.hide();
        core.toast(t('admin_products_added_local', { name: values.name }));
      } else if (isLocalId(editId)) {
        const index = overlay.created.findIndex(item => asId(item.id) === editId);
        if (index >= 0) overlay.created[index] = { ...overlay.created[index], ...values, id: editId };
        persistOverlay();
        productModal.hide();
        core.toast(t('admin_products_updated_local', { name: values.name }));
      } else {
        const previousPatch = overlay.patches[editId] || {};
        const editedProduct = currentRows.find(item => item.id === editId);
        const base = previousPatch._base || (editedProduct ? {
          name: editedProduct.name,
          categoryId: editedProduct.categoryId,
          status: editedProduct.status
        } : null);
        overlay.patches[editId] = { ...previousPatch, ...(base ? { _base: base } : {}), ...values };
        persistOverlay();
        productModal.hide();
        core.toast(t('admin_products_updated_local', { name: values.name }));
      }
      currentPage = 1;
      await loadProducts();
    } catch (error) {
      console.warn('Admin product overlay write failed:', error);
      core.toast(t('admin_products_write_error'), 'error');
    } finally {
      core.setBusy(saveButton, false);
    }
  }

  async function deleteProduct(product) {
    const local = isLocalId(product.id);
    const confirmed = await core.confirm({
      title: t('admin_products_delete_title', { name: product.name }),
      message: t(local ? 'admin_products_delete_local_message' : 'admin_products_delete_live_message'),
      confirmLabel: t('admin_products_delete_confirm')
    });
    if (!confirmed) return;

    try {
      if (local) {
        overlay.created = overlay.created.filter(item => asId(item.id) !== product.id);
      } else {
        const previousPatch = overlay.patches[product.id];
        overlay.hiddenMeta[product.id] = {
          categoryId: asId(previousPatch?._base?.categoryId || product.categoryId)
        };
        overlay.hiddenIds = [...new Set([...overlay.hiddenIds.map(asId), product.id])];
        delete overlay.patches[product.id];
      }
      persistOverlay();
      if (currentRows.length === 1 && currentPage > 1) currentPage -= 1;
      core.toast(t(local ? 'admin_products_removed_local' : 'admin_products_hidden_local', { name: product.name }));
      await loadProducts();
    } catch (error) {
      console.warn('Admin product overlay delete failed:', error);
      core.toast(t('admin_products_write_error'), 'error');
    }
  }

  function bindEvents() {
    byId('addProductButton').addEventListener('click', () => openProductEditor());
    byId('productEditorForm').addEventListener('submit', saveProduct);
    byId('productImage').addEventListener('input', updateImagePreview);
    byId('productEditorModal').addEventListener('hidden.bs.modal', clearValidation);

    byId('productFilters').addEventListener('submit', event => {
      event.preventDefault();
      currentPage = 1;
      loadProducts();
    });
    byId('productSearch').addEventListener('input', () => {
      clearTimeout(searchTimer);
      searchTimer = setTimeout(() => {
        currentPage = 1;
        loadProducts();
      }, 320);
    });
    ['productCategoryFilter', 'productStatusFilter', 'productSort'].forEach(id => {
      byId(id).addEventListener('change', () => {
        currentPage = 1;
        loadProducts();
      });
    });
    byId('resetProductFilters').addEventListener('click', resetFilters);

    byId('productTableBody').addEventListener('click', event => {
      const button = event.target.closest('[data-product-action]');
      const row = button?.closest('[data-product-id]');
      if (!button || !row) return;
      const product = currentRows.find(item => item.id === row.dataset.productId);
      if (!product) return;
      if (button.dataset.productAction === 'edit') openProductEditor(product);
      if (button.dataset.productAction === 'delete') deleteProduct(product);
    });

    byId('productPrevious').addEventListener('click', () => {
      if (currentPage <= 1) return;
      currentPage -= 1;
      loadProducts();
    });
    byId('productNext').addEventListener('click', () => {
      if (currentPage >= totalPages) return;
      currentPage += 1;
      loadProducts();
    });
    byId('productPageButtons').addEventListener('click', event => {
      const button = event.target.closest('[data-product-page]');
      if (!button) return;
      currentPage = Number(button.dataset.productPage) || 1;
      loadProducts();
    });

    window.addEventListener('am:langchange', () => {
      rebuildCategoryOptions();
      if (currentRows.length) renderProducts();
      const editId = byId('productEditId').value;
      byId('productEditorTitle').textContent = t(editId ? 'admin_products_edit_title' : 'admin_products_add_title');
    });
  }

  async function initProducts(event) {
    core = event.detail?.core || window.AdminCore;
    if (!core) return;
    productStorageKey = core.storageKeys?.products || core.keys?.products || 'am_admin_products_v1';
    categoryStorageKey = core.storageKeys?.categories || core.keys?.categories || 'am_admin_categories_v1';
    overlay = sanitizeOverlay(core.read(productStorageKey, emptyOverlay()));
    productModal = bootstrap.Modal.getOrCreateInstance(byId('productEditorModal'));
    bindEvents();

    showState('loading', t('admin_products_loading_title'), t('admin_products_loading_body'));
    try {
      await ensureCategories();
      rebuildCategoryOptions();
      await loadProducts();
    } catch (error) {
      console.warn('Admin product initialization failed:', error);
      showState(
        'error',
        t('admin_products_error_title'),
        t('admin_products_error_body'),
        t('admin_products_retry'),
        async () => {
          try {
            await ensureCategories();
            rebuildCategoryOptions();
            await loadProducts();
          } catch (retryError) {
            console.warn('Admin product retry failed:', retryError);
          }
        }
      );
    }
  }

  window.addEventListener('admin:ready', initProducts, { once: true });
})();
