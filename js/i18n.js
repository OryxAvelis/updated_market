// Translate an API category name for the current language (FR shows it as-is)
function catName(name) {
  if (!name) return name || '';
  if (getLang() === 'fr') return name;
  return CAT_EN[String(name).toLowerCase().trim()] || name;
}

function getLang() {
  const l = localStorage.getItem('am_lang');
  return (l === 'fr' || l === 'en') ? l : 'fr';
}

function t(key, vars) {
  const lang = getLang();
  let s = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

function applyI18n(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  // innerHTML only for whitelisted keys whose values are trusted, developer-managed
  // markup constants in I18N (no user/network data ever interpolated into them).
  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (I18N_HTML_KEYS[key]) el.innerHTML = t(key);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  document.documentElement.lang = getLang();
  const page = document.body?.dataset.page;
  const pageTitleKey = page ? 'title_' + page.replace(/-/g, '_') : '';
  if (pageTitleKey && I18N[getLang()]?.[pageTitleKey]) document.title = t(pageTitleKey);
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta_description'));
  document.querySelector('meta[property="og:title"]')?.setAttribute('content', document.title);
  document.querySelector('meta[property="og:description"]')?.setAttribute('content', t('meta_description'));
  const lbl = document.getElementById('langLabel');
  if (lbl) lbl.textContent = getLang() === 'en' ? 'EN' : 'FR';
}

function setLang(lang, options = {}) {
  const value = lang === 'en' ? 'en' : 'fr';
  localStorage.setItem('am_lang', value);
  applyI18n();
  window.dispatchEvent(new CustomEvent('am:langchange', { detail: { lang: value } }));
  if (options.persist !== false && window.StoreAPI && typeof getUser === 'function' && getUser()) {
    StoreAPI.preferences.update({ language: value }).catch(error => console.error(error));
  }
}

function toggleLang() {
  setLang(getLang() === 'en' ? 'fr' : 'en');
}

document.addEventListener('DOMContentLoaded', () => {
  applyI18n();
  document.querySelectorAll('[data-lang-toggle]').forEach(b => b.addEventListener('click', toggleLang));
});
